const FAVICON_SVG = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="#101916"/><path d="M14 30 32 14 50 30v23H14Z" fill="none" stroke="#edbd77" stroke-width="4"/><path d="M20 38h24M20 46h24" stroke="#edbd77" stroke-width="4"/></svg>\n`;

const canonical = source => source.replace(/\r\n/g, '\n');

function replaceExactlyOnce(source, anchor, replacement, label) {
  const count = typeof anchor === 'string'
    ? source.split(anchor).length - 1
    : (source.match(new RegExp(anchor.source, anchor.flags.includes('g') ? anchor.flags : anchor.flags + 'g')) ?? []).length;
  if (count !== 1) throw new Error(`Solo build: ${label} expected exactly one anchor, found ${count}.`);
  return source.replace(anchor, replacement);
}

// Standalone publishing transform of the unchanged source index.html.
export function deriveSoloHtml(htmlSource) {
  let source = canonical(htmlSource);
  source = replaceExactlyOnce(source, /<link rel="icon" href="data:[^"]*">/, '<link rel="icon" href="./favicon.svg">', 'data: favicon');
  source = replaceExactlyOnce(source, /<script type="module">[\s\S]*?<\/script>/, '<script type="module" src="./game.js"></script>', 'inline module bootstrap');
  source = source.replace(/\s+onclick="[^"]*"/g, '');
  if (/ on\w+="/.test(source)) throw new Error('Solo build: unexpected inline event handler left in index.html.');
  source = replaceExactlyOnce(source, 'href="/"', 'href="./index.html"', 'brand link');
  source = source.replace(/(href|src)="\/(?!\/)/g, '$1="./');
  if (/(?:href|src)="\//.test(source)) throw new Error('Solo build: absolute path left in index.html.');
  return '<!-- GENERATED by scripts/build-solo.mjs from public/index.html; do not edit the copy. -->\n' + source;
}

function upstreamCommit(root) {
  try {
    const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
    return /^[0-9a-f]{40}$/.test(commit) ? commit : 'unknown';
  } catch {
    return 'unknown';
  }
}

