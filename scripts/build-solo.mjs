// Bounded static browser export builder for the solo edition.
// Bundles public/solo-entry.js into dist-solo/game.js and assembles a
// self-contained static directory (index.html, style.css, media, licences and
// the LOB7 manifest) that any static file server can publish. No network or
// GitHub calls; everything resolves from this repository and node_modules.
import * as esbuild from 'esbuild';
import { realpathSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { access, copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { basename, dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const UPSTREAM_URL = 'https://github.com/cedricbernadac/deadwood-open';
export const UPSTREAM_COMMIT = '35ee1efed1bb448f9e2b6d66f7a6915e0e16bf90';
export const OUTPUT_DIRECTORY = 'dist-solo';

const MEDIA_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.svg', '.glb', '.gltf', '.bin', '.ktx2', '.wav', '.mp3', '.ogg', '.json']);
// Matches a media extension but is a development fixture, not a runtime asset.
const EXCLUDED_PUBLIC_FILES = new Set(['weapon-damage-before.json']);

const LIMITS = { files: 499, expandedBytes: 256 * 1024 ** 2, archiveBytes: 100 * 1024 ** 2 };
// Extensions that compress inside the archive; the rest ship at raw size.
const COMPRESSIBLE_EXTENSIONS = new Set(['.html', '.css', '.js', '.json', '.svg', '.md', '.gltf', '']);

const VENDOR_MODULES = new Map([
  ['/vendor/three.module.js', 'three/build/three.module.js'],
  ['/vendor/three.core.js', 'three/build/three.core.js'],
  ['/vendor/GLTFLoader.js', 'three/examples/jsm/loaders/GLTFLoader.js'],
  ['/vendor/BufferGeometryUtils.js', 'three/examples/jsm/utils/BufferGeometryUtils.js'],
  ['/vendor/Reflector.js', 'three/examples/jsm/objects/Reflector.js'],
]);

