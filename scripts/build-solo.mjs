// Absolute /vendor/* specifiers used by the proven LAN sources resolve to the
// installed three package; any other absolute import fails the build.
function vendorPlugin(root) {
  return {
    name: 'deadwood-solo-vendor',
    setup(build) {
      build.onResolve({ filter: /^\/vendor\// }, async args => {
        const target = VENDOR_MODULES.get(args.path);
        if (!target) throw new Error(`Solo build: unknown vendor module ${args.path} imported from ${args.importer || 'entry'}.`);
        const resolved = join(root, 'node_modules', ...target.split('/'));
        await access(resolved);
        return { path: resolved };
      });
      build.onResolve({ filter: /^\// }, args => {
        throw new Error(`Solo build: absolute import ${args.path} from ${args.importer || 'entry'} cannot ship in a static export.`);
      });
      build.onLoad({ filter: /[\\/]GLTFLoader\.js$/ }, async args => ({
        // Avoid an inert diagnostic being mistaken for an import by the static
        // recipe's lexical import check. Loading behavior is unchanged.
        contents: (await readFile(args.path, 'utf8')).replace('Converting vertex colors from "srgb-linear" to', 'Converting vertex colors out of the srgb-linear color space to'),
        loader: 'js',
      }));
    },
  };
}

async function copyPublicAssets(publicDirectory, outDir) {
  const copied = [];
  async function walk(directory) {
    for (const item of await readdir(directory, { withFileTypes: true })) {
      if (item.name.startsWith('.')) continue;
      const full = join(directory, item.name);
      if (item.isDirectory()) { await walk(full); continue; }
      const rel = relative(publicDirectory, full).split(sep).join('/');
      // The cabin is procedural. Other maps stay in development sources only.
      if (rel.startsWith('levels/')) continue;
      const extension = extname(item.name).toLowerCase();
      const wanted = ['style.css', 'frisson/frisson.css', 'frisson/feedback.css'].includes(rel) || (MEDIA_EXTENSIONS.has(extension) && !EXCLUDED_PUBLIC_FILES.has(rel));
      if (!wanted) continue;
      const target = join(outDir, ...rel.split('/'));
      await mkdir(dirname(target), { recursive: true });
      await copyFile(full, target);
      copied.push(rel);
    }
  }
  await walk(publicDirectory);
  return copied.sort();
}

async function exportContents(outDir) {
  const files = [];
  async function walk(directory) {
    for (const item of await readdir(directory, { withFileTypes: true })) {
      const full = join(directory, item.name);
      if (item.isDirectory()) { await walk(full); continue; }
      files.push(full);
    }
  }
  await walk(outDir);
  return files.sort();
}

const FORBIDDEN_NAMES = new Set(['package.json', 'package-lock.json', 'node_modules', '.work']);
function assertCleanExport(files, outDir) {
  const allowedExtensions = new Set([...MEDIA_EXTENSIONS, '.html', '.css', '.js', '.md', '']);
  const offenders = [];
  for (const file of files) {
    const rel = relative(outDir, file).split(sep).join('/');
    const parts = rel.split('/');
    const name = parts.at(-1);
    if (parts.some(part => part.startsWith('.') || FORBIDDEN_NAMES.has(part)) || FORBIDDEN_NAMES.has(name)
      || name.includes('.test.') || (!allowedExtensions.has(extname(name).toLowerCase()) && name !== 'LICENSE')) offenders.push(rel);
  }
  if (offenders.length) throw new Error(`Solo build: unsupported files in export: ${offenders.join(', ')}`);
}

export async function buildSolo(directory = resolve(dirname(fileURLToPath(import.meta.url)), '..'), { entry = join('public', 'solo-entry.js') } = {}) {
  const root = resolve(directory);
  const outDir = resolve(root, OUTPUT_DIRECTORY);
  if (dirname(outDir) !== root || basename(outDir) !== OUTPUT_DIRECTORY)
    throw new Error(`Solo build: refusing to replace anything but this repository's ${OUTPUT_DIRECTORY}/ (got ${outDir}).`);

  const entryPoint = resolve(root, entry);
  await access(entryPoint).catch(() => {
    throw new Error(`Solo build: ${relative(root, entryPoint)} is missing; the solo entry point is provided elsewhere in this repository.`);
  });

  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  const bundle = await esbuild.build({
    entryPoints: [entryPoint],
    outfile: join(outDir, 'game.js'),
    bundle: true,
    splitting: false,
    minify: false,
    format: 'esm',
    target: 'es2022',
    platform: 'browser',
    treeShaking: true,
    tsconfigRaw: {},
    plugins: [vendorPlugin(root)],
    logLevel: 'silent',
  });
  if (bundle.errors.length) throw new Error(`Solo build: esbuild failed: ${bundle.errors.map(error => error.text).join('; ')}`);

  const publicDirectory = join(root, 'public');
  await copyPublicAssets(publicDirectory, outDir);
  await writeFile(join(outDir, 'index.html'), deriveSoloHtml(await readFile(join(publicDirectory, 'index.html'), 'utf8')));
  await writeFile(join(outDir, 'favicon.svg'), FAVICON_SVG);
  await writeFile(join(outDir, 'LOB7-GAME.json'), JSON.stringify(SOLO_MANIFEST, null, 2) + '\n');
  try { await copyFile(join(root, 'LOB7-ATTRIBUTION.json'), join(outDir, 'LOB7-ATTRIBUTION.json')); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  await copyFile(join(root, 'LICENSE'), join(outDir, 'LICENSE'));
  await writeFile(join(outDir, 'ASSETS-LICENSE.md'), await readFile(join(root, 'ASSETS.md'), 'utf8'));
  await writeFile(join(outDir, 'NOTICE.md'), noticeText(upstreamCommit(root)) + '\n## Three.js MIT licence\n\n' + await readFile(join(root, 'node_modules/three/LICENSE'), 'utf8'));
  await writeFile(join(outDir, 'README.md'), `# Deadwood Solo Open\n\nPublished by Nilo. Created with Codex, Claude and Kimi.\n\n[Play on LOB7](https://lob7.com/games/bg_s_07513039-c17e-4900-afac-bb2509cac6c4).\n\nThis branch is a self-contained static edition: one survivor and the cabin, with the original twenty-wave campaign plus Last Night: ten timed waves, about five minutes. Choose the mode before preparing your night. Last Night allows pausing but has no mid-run saves. The game simulation runs entirely in your browser. Serve this directory with any static web server and open index.html. No gameplay backend or API key is needed.\n\nBuild tooling, original modules, tests and the implementation plan are on the [development branch](https://github.com/codex-lm/deadwood-solo-open/tree/${upstreamCommit(root)}).\n\nCode is MIT; media are CC BY 4.0. See LICENSE, ASSETS-LICENSE.md and NOTICE.md for the preserved upstream attribution and dependency notices.\n`);

  const files = await exportContents(outDir);
  assertCleanExport(files, outDir);
  let expandedBytes = 0, archiveBytes = 0;
  for (const file of files) {
    const content = await readFile(file);
    expandedBytes += content.length;
    archiveBytes += COMPRESSIBLE_EXTENSIONS.has(extname(file).toLowerCase()) ? gzipSync(content).length : content.length;
  }
  const mib = bytes => (bytes / 1024 ** 2).toFixed(1);
  if (files.length > LIMITS.files) throw new Error(`Solo build: ${files.length} files exceed the ${LIMITS.files}-file limit.`);
  if (expandedBytes > LIMITS.expandedBytes) throw new Error(`Solo build: ${mib(expandedBytes)} MiB expanded exceed the 256 MiB limit.`);
  if (archiveBytes > LIMITS.archiveBytes) throw new Error(`Solo build: ~${mib(archiveBytes)} MiB archive estimate exceeds the 100 MiB limit.`);
  return { directory: outDir, files: files.length, expandedBytes, archiveBytes };
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  buildSolo().then(({ files, expandedBytes, archiveBytes }) => {
    const mib = bytes => (bytes / 1024 ** 2).toFixed(1);
    console.log(`${OUTPUT_DIRECTORY}: ${files} files, ${mib(expandedBytes)} MiB expanded, ~${mib(archiveBytes)} MiB archive estimate.`);
  }).catch(error => { console.error(error.message ?? error); process.exitCode = 1; });
}
